-- ═══════════════════════════════════════════════════════════════
-- receta SCHEMA — recipe master data (process engineering domain)
--
-- Domain split:
--   receta.tenido         → dyeing recipe formula
--   receta.lavado_maquina → machine wash recipe formula
--   receta.operacion      → chemistry step catalog
--
-- NOTE: receta.operacion  = micro-level chemistry steps within a recipe
--       mes.operacion     = macro-level production operations (TENIDO, SECADO…)
--       Same name, different granularity, different schema, never JOINed together.
--
-- Consumers:
--   mes.orden_produccion_paso.receta_id    → receta.tenido(id)
--   mes.lavado_maquina.receta_id           → receta.lavado_maquina(id)
-- ═══════════════════════════════════════════════════════════════

CREATE SCHEMA IF NOT EXISTS receta;

-- ───────────────────────────────────────
-- Chemistry operation catalog
-- ───────────────────────────────────────

CREATE TABLE receta.operacion (
    id           SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    codigo       TEXT NOT NULL UNIQUE,
    codigo_canon TEXT NOT NULL UNIQUE,
    nombre       TEXT NOT NULL
);

CREATE TRIGGER trg_bi_receta_operacion_codigo_canon
BEFORE INSERT OR UPDATE ON receta.operacion
FOR EACH ROW
EXECUTE FUNCTION fn_trg_set_codigo_canon();

