-- ───────────────────────────────────────
-- Dyeing recipe header
-- (migrated from public.receta2)
-- ───────────────────────────────────────

CREATE TABLE receta.tenido (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    color_x_cliente_id INT     REFERENCES color_x_cliente(id),
    tipo_articulo_id   INT     REFERENCES tipo_articulo(id),
    tenido_id          INT     REFERENCES tenido(id),
    fibra              SMALLINT,
    tipo_receta_id     SMALLINT REFERENCES tipo_receta(id),
    flg_activo         BOOLEAN  DEFAULT true,
    flg_antipilling    BOOLEAN  DEFAULT false,
    flg_produccion     BOOLEAN  DEFAULT false,
    fyh_produccion     TIMESTAMPTZ,
    usr_cre            INT      REFERENCES profiles(id_usuario),
    fyh_cre            TIMESTAMPTZ DEFAULT now(),
    usr_mod            INT      REFERENCES profiles(id_usuario),
    fyh_mod            TIMESTAMPTZ
);

-- Dyeing recipe steps (ordered chemistry sequence within the recipe)
CREATE TABLE receta.tenido_paso (
    id           INT      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    receta_id    INT      NOT NULL REFERENCES receta.tenido(id),
    operacion_id SMALLINT NOT NULL REFERENCES receta.operacion(id),
    orden        SMALLINT NOT NULL,
    ph           NUMERIC(4,2),
    temperatura  NUMERIC(5,2),
    tiempo_min   SMALLINT,
    nota         TEXT,
    UNIQUE(receta_id, orden)
);

-- Chemicals per dyeing step
CREATE TABLE receta.tenido_paso_insumo (
    id       INT             GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    paso_id  INT             NOT NULL REFERENCES receta.tenido_paso(id) ON DELETE CASCADE,
    item_id  INT             NOT NULL REFERENCES item(id),
    cantidad NUMERIC(8,4)   NOT NULL,
    orden    SMALLINT        NOT NULL,
    UNIQUE(paso_id, orden)
);

-- ───────────────────────────────────────
-- Machine wash recipe header
-- (migrated from public.receta_lavado_maquina)
-- ───────────────────────────────────────

CREATE TABLE receta.lavado_maquina (
    id                INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_lavado_mq_id SMALLINT REFERENCES tipo_lavado_maquina(id),
    valor_origen_id   SMALLINT REFERENCES valor(id),
    valor_destino_id  SMALLINT REFERENCES valor(id),
    flg_activo        BOOLEAN  DEFAULT true,
    usr_cre           INT      REFERENCES profiles(id_usuario),
    fyh_cre           TIMESTAMPTZ DEFAULT now(),
    usr_mod           INT      REFERENCES profiles(id_usuario),
    fyh_mod           TIMESTAMPTZ
);

-- Wash recipe steps
CREATE TABLE receta.lavado_maquina_paso (
    id           INT      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    receta_id    INT      NOT NULL REFERENCES receta.lavado_maquina(id),
    operacion_id SMALLINT NOT NULL REFERENCES receta.operacion(id),
    orden        SMALLINT NOT NULL,
    ph           NUMERIC(4,2),
    temperatura  NUMERIC(5,2),
    tiempo_min   SMALLINT,
    nota         TEXT,
    UNIQUE(receta_id, orden)
);

-- Chemicals per wash step
CREATE TABLE receta.lavado_maquina_paso_insumo (
    id       INT           GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    paso_id  INT           NOT NULL REFERENCES receta.lavado_maquina_paso(id) ON DELETE CASCADE,
    item_id  INT           NOT NULL REFERENCES item(id),
    cantidad NUMERIC(8,4)  NOT NULL,
    orden    SMALLINT      NOT NULL,
    UNIQUE(paso_id, orden)
);

-- ───────────────────────────────────────
-- GRANTS
-- ───────────────────────────────────────

GRANT USAGE ON SCHEMA receta TO authenticated;
GRANT SELECT ON receta.operacion                  TO authenticated;
GRANT SELECT ON receta.tenido                     TO authenticated;
GRANT SELECT ON receta.tenido_paso                TO authenticated;
GRANT SELECT ON receta.tenido_paso_insumo         TO authenticated;
GRANT SELECT ON receta.lavado_maquina             TO authenticated;
GRANT SELECT ON receta.lavado_maquina_paso        TO authenticated;
GRANT SELECT ON receta.lavado_maquina_paso_insumo TO authenticated;


