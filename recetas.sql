CREATE TABLE IF NOT EXISTS public.desarrollo_color
(
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1 ),
    color_x_cliente_id smallint,
    tipo_articulo_id smallint,
    tenido_id smallint,
    fecha_ingreso date NOT NULL,
    estado_desarrollo_color_id smallint,
    fecha_estado_actual date,
    descripcion text COLLATE pg_catalog."default",
    fyh_cre timestamp without time zone DEFAULT now(),
    fyh_cre_tz timestamp with time zone DEFAULT now(),
    CONSTRAINT desarrollo_color_pkey PRIMARY KEY (id),
    CONSTRAINT uq_desarrollo UNIQUE (color_x_cliente_id, tipo_articulo_id, tenido_id),
    CONSTRAINT desarrollo_color_fk_color_x_cliente_fkey FOREIGN KEY (color_x_cliente_id)
        REFERENCES public.color_x_cliente (id) MATCH SIMPLE ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT desarrollo_color_fk_estado_desarrollo_color_fkey FOREIGN KEY (estado_desarrollo_color_id)
        REFERENCES public.estado_desarrollo_color (id) MATCH SIMPLE ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT desarrollo_color_fk_tenido_fkey FOREIGN KEY (tenido_id)
        REFERENCES public.tenido (id) MATCH SIMPLE ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT desarrollo_color_fk_tipo_articulo_fkey FOREIGN KEY (tipo_articulo_id)
        REFERENCES public.tipo_articulo (id) MATCH SIMPLE ON UPDATE NO ACTION ON DELETE NO ACTION
);


