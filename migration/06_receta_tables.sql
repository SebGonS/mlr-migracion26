-- ── receta.tenido ──────────────────────────────────────────────
-- articulo_tipo_id + fibra: recipe is defined at article-type/fiber level,
-- not per specific articulo (color variant). Multiple articulos of the same
-- type and fiber share the same recipe.
CREATE TABLE receta.tenido (
    id                 INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    color_x_cliente_id INT      REFERENCES color_x_cliente(id),
    articulo_tipo_id   SMALLINT REFERENCES articulo_tipo(id),
    fibra              SMALLINT,
    tenido_id          INT      REFERENCES tenido(id),
    flg_antipilling    BOOLEAN  NOT NULL DEFAULT false,
    tipo_receta_id     SMALLINT NOT NULL REFERENCES tipo_receta(id),
    estado_id          SMALLINT NOT NULL REFERENCES estado_desarrollo_color(id),
    flg_produccion     BOOLEAN  NOT NULL DEFAULT false,
    fyh_produccion     TIMESTAMPTZ,
    usr_cre            INT      REFERENCES usuario(id),
    fyh_cre            TIMESTAMPTZ DEFAULT now(),
    usr_mod            INT      REFERENCES usuario(id),
    fyh_mod            TIMESTAMPTZ
);

CREATE OR REPLACE FUNCTION fn_trg_receta_tenido_flg_produccion()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_aprobado_id SMALLINT;
BEGIN
    SELECT id INTO v_aprobado_id FROM estado_desarrollo_color WHERE codigo = 'APROBADO';
    NEW.flg_produccion := (NEW.estado_id = v_aprobado_id);
    RETURN NEW;
END;$$;

CREATE TRIGGER trg_bi_receta_tenido_flg_produccion
BEFORE INSERT OR UPDATE OF estado_id ON receta.tenido
FOR EACH ROW EXECUTE FUNCTION fn_trg_receta_tenido_flg_produccion();

CREATE UNIQUE INDEX uq_receta_tenido_aprobada
    ON receta.tenido(color_x_cliente_id, articulo_tipo_id, fibra, tenido_id, flg_antipilling)
    WHERE flg_produccion = true;

-- ── receta.tenido_paso ────────────────────────────────────────
CREATE TABLE receta.tenido_paso (
    id           INT      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    receta_id    INT      NOT NULL REFERENCES receta.tenido(id),
    operacion_id SMALLINT NOT NULL REFERENCES receta.operacion(id),
    orden        SMALLINT NOT NULL,
    ph           NUMERIC(4,2),
    temperatura  NUMERIC(5,2),
    tiempo_min   SMALLINT,
    nota         TEXT,
    UNIQUE(receta_id, orden)
);

-- ── receta.tenido_paso_insumo ─────────────────────────────────
CREATE TABLE receta.tenido_paso_insumo (
    id       INT            GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    paso_id  INT            NOT NULL REFERENCES receta.tenido_paso(id) ON DELETE CASCADE,
    item_id  INT            NOT NULL REFERENCES item(id),
    cantidad NUMERIC(10,6)  NOT NULL,  -- 10,6: max 9999.999999 (NUMERIC(8,6) would limit integer part to 99)
    medida   TEXT           NOT NULL DEFAULT 'g_kg' CHECK (medida IN ('g_kg', 'pct')),
    orden    SMALLINT       NOT NULL,
    UNIQUE(paso_id, orden)
);

-- ── receta.tenido immutability ───────────────────────────────
-- Prevent modifying a dyeing recipe once it has completed production executions.
-- Estado/audit cols remain writable (lifecycle transitions must still be possible).
-- Same pattern as receta.lavado_maquina below.
-- NOTE: references mes.partida_paso/ejecucion defined in 07_... — resolved at runtime.

CREATE OR REPLACE FUNCTION receta.fn_trg_tenido_immutable()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM mes.partida_paso pp
        JOIN mes.partida_paso_ejecucion pe ON pe.partida_paso_id = pp.id
        WHERE pp.receta_id = OLD.id
          AND pe.estado = 'COMPLETADO'
    ) THEN
        RAISE EXCEPTION
            'receta.tenido id=% cannot be modified: it has completed production executions',
            OLD.id;
    END IF;
    RETURN NEW;
END;
$$;

-- Guard identity fields only; estado_id/audit cols remain writable.
-- flg_antipilling is excluded: it is derived by trigger from tenido_paso operacion presence.
CREATE TRIGGER trg_bu_tenido_immutable
BEFORE UPDATE OF color_x_cliente_id, articulo_tipo_id, fibra, tenido_id, tipo_receta_id
ON receta.tenido
FOR EACH ROW EXECUTE FUNCTION receta.fn_trg_tenido_immutable();

CREATE OR REPLACE FUNCTION receta.fn_trg_tenido_paso_immutable()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_receta_id INT := COALESCE(OLD.receta_id, NEW.receta_id);
BEGIN
    IF EXISTS (
        SELECT 1
        FROM mes.partida_paso pp
        JOIN mes.partida_paso_ejecucion pe ON pe.partida_paso_id = pp.id
        WHERE pp.receta_id = v_receta_id
          AND pe.estado = 'COMPLETADO'
    ) THEN
        RAISE EXCEPTION
            'receta.tenido_paso id=% cannot be modified: its recipe has completed executions',
            OLD.id;
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;

CREATE TRIGGER trg_bud_tenido_paso_immutable
BEFORE UPDATE OF operacion_id, orden, ph, temperatura, tiempo_min
ON receta.tenido_paso
FOR EACH ROW EXECUTE FUNCTION receta.fn_trg_tenido_paso_immutable();

CREATE TRIGGER trg_bd_tenido_paso_immutable
BEFORE DELETE ON receta.tenido_paso
FOR EACH ROW EXECUTE FUNCTION receta.fn_trg_tenido_paso_immutable();

CREATE OR REPLACE FUNCTION receta.fn_trg_tenido_paso_insumo_immutable()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_receta_id INT;
BEGIN
    SELECT tp.receta_id INTO v_receta_id
    FROM receta.tenido_paso tp
    WHERE tp.id = COALESCE(OLD.paso_id, NEW.paso_id);

    IF EXISTS (
        SELECT 1
        FROM mes.partida_paso pp
        JOIN mes.partida_paso_ejecucion pe ON pe.partida_paso_id = pp.id
        WHERE pp.receta_id = v_receta_id
          AND pe.estado = 'COMPLETADO'
    ) THEN
        RAISE EXCEPTION
            'receta.tenido_paso_insumo id=% cannot be modified: its recipe has completed executions',
            OLD.id;
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;

CREATE TRIGGER trg_bud_tenido_paso_insumo_immutable
BEFORE UPDATE OF item_id, cantidad, medida, orden
ON receta.tenido_paso_insumo
FOR EACH ROW EXECUTE FUNCTION receta.fn_trg_tenido_paso_insumo_immutable();

CREATE TRIGGER trg_bd_tenido_paso_insumo_immutable
BEFORE DELETE ON receta.tenido_paso_insumo
FOR EACH ROW EXECUTE FUNCTION receta.fn_trg_tenido_paso_insumo_immutable();


