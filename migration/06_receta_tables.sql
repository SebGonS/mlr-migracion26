CREATE TABLE receta.lavado_maquina (
    id                INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_lavado_mq_id SMALLINT REFERENCES tipo_lavado_maquina(id),
    valor_origen_id   SMALLINT REFERENCES valor(id),
    valor_destino_id  SMALLINT REFERENCES valor(id),
    flg_activo        BOOLEAN  DEFAULT true,
    usr_cre           INT      REFERENCES usuario(id),
    fyh_cre           TIMESTAMPTZ DEFAULT now(),
    usr_mod           INT      REFERENCES usuario(id),
    fyh_mod           TIMESTAMPTZ
);

-- Only one active recipe per (machine type, from-value, to-value) transition.
CREATE UNIQUE INDEX uq_receta_lavado_maquina_activa
    ON receta.lavado_maquina(tipo_lavado_mq_id, valor_origen_id, valor_destino_id)
    WHERE flg_activo = true;

-- Prevent editing a recipe that has already been executed.
CREATE OR REPLACE FUNCTION receta.fn_trg_lavado_maquina_immutable()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM mes.lavado_maquina
        WHERE receta_id = OLD.id AND estado = 'COMPLETADO'
    ) THEN
        RAISE EXCEPTION
            'receta.lavado_maquina id=% cannot be modified: it has completed executions',
            OLD.id;
    END IF;
    RETURN NEW;
END;
$$;

-- Only guard the three definition fields; flg_activo / audit cols can still be updated
-- even when the recipe has completed executions (activate/deactivate remains possible).
CREATE TRIGGER trg_bu_lavado_maquina_immutable
BEFORE UPDATE OF tipo_lavado_mq_id, valor_origen_id, valor_destino_id ON receta.lavado_maquina
FOR EACH ROW EXECUTE FUNCTION receta.fn_trg_lavado_maquina_immutable();

