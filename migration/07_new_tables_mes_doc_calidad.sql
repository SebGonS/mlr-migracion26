-- ── doc.partida ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS doc.partida (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    numero int GENERATED BY DEFAULT AS IDENTITY,
    prioridad_id int REFERENCES prioridad(id),
    tercero_id INT NOT NULL REFERENCES tercero(id),
    tenido_id int NOT NULL REFERENCES tenido(id),
    color_x_cliente_id int NOT NULL REFERENCES color_x_cliente(id),
    articulo_tipo_id SMALLINT NOT NULL REFERENCES articulo_tipo(id),  -- fabric type for this batch (billing key); restricts assignable rolls
    malla text,
    rendimiento text,
    ancho text,
    flg_antipilling boolean NOT NULL DEFAULT false,
    fecha_acordada date,                           -- agreed delivery date with client (SAP: EDATU)
    estado partida_estado_enum NOT NULL DEFAULT 'CREADA',
    -- Billing axis — orthogonal to production state.
    -- Updated when doc.factura lines are issued against this order.
    estado_facturacion partida_facturacion_enum NOT NULL DEFAULT 'pendiente',
    fyh_programacion timestamptz,
    fyh_inicio timestamptz,
    fyh_fin timestamptz,
    usr_cre int,
    fyh_cre TIMESTAMPTZ DEFAULT NOW(),
    usr_mod int,
    fyh_mod TIMESTAMPTZ,
    flg_elm BOOL DEFAULT false,
    usr_elm INT,
    fyh_elm TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS doc.partida_detalle (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    partida_id bigint NOT NULL REFERENCES doc.partida(id),
