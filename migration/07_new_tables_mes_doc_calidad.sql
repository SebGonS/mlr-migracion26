    fecha_recepcion TIMESTAMPTZ DEFAULT now(),
    usr_cre int,
    fyh_cre timestamptz DEFAULT NOW(),
    usr_mod int,
    fyh_mod timestamptz,
    usr_elm INT,
    fyh_elm TIMESTAMPTZ,
    CONSTRAINT chk_guia_doc_fields CHECK ((serie IS NULL) = (correlativo IS NULL)),
    UNIQUE (tercero_id, serie, correlativo, guia_remision_tipo_id)
);

