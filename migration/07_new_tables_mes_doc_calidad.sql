-- tipo_comprobante codes follow SUNAT standard:
--   '01' = Factura        (RUC buyer, full tax credit)
--   '03' = Boleta de Venta (DNI/RUC buyer, no credit)
--   '07' = Nota de Crédito
--   '08' = Nota de Débito
CREATE TABLE doc.factura (
    id                  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tipo_comprobante    CHAR(2) NOT NULL DEFAULT '01'
                            CHECK (tipo_comprobante IN ('01','03','07','08')),
    serie               TEXT NOT NULL,          -- e.g. F001, B001, T001
    numero              INT  NOT NULL,          -- correlative
    tercero_id          INT  NOT NULL REFERENCES tercero(id),
    fecha_emision       DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_vencimiento   DATE,
    moneda              CHAR(3) NOT NULL DEFAULT 'PEN',
    tipo_cambio         NUMERIC(10,4),          -- only relevant when moneda = 'USD'
    subtotal            NUMERIC(12,2) NOT NULL DEFAULT 0,
    igv                 NUMERIC(12,2) NOT NULL DEFAULT 0,   -- 18 % standard rate
    total               NUMERIC(12,2) NOT NULL DEFAULT 0,
    estado              factura_estado_enum NOT NULL DEFAULT 'borrador',
    -- Nota de crédito/débito linkage (nullable — only set for 07/08 types)
    factura_origen_id   BIGINT REFERENCES doc.factura(id),
    observacion         TEXT,
    usr_cre INT, fyh_cre TIMESTAMPTZ DEFAULT NOW(),
    usr_mod INT, fyh_mod TIMESTAMPTZ,
    flg_elm BOOL DEFAULT false,
    usr_elm INT, fyh_elm TIMESTAMPTZ,
    UNIQUE (serie, numero),
    CONSTRAINT chk_factura_montos CHECK (
        subtotal >= 0 AND igv >= 0 AND total >= 0
        AND ABS(total - (subtotal + igv)) < 0.01
    ),
    CONSTRAINT chk_nota_requiere_origen CHECK (
        tipo_comprobante NOT IN ('07','08') OR factura_origen_id IS NOT NULL
    )
);

-- ── doc.factura_detalle ────────────────────────────────────────
-- One line per billable item / service.
-- partida_id links back to the sales order for billing-to-order reconciliation.
-- igv_porcentaje allows 0% for IGV-exempt items (e.g. exported goods).
CREATE TABLE doc.factura_detalle (
    id                  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    factura_id          BIGINT NOT NULL REFERENCES doc.factura(id),
    -- Sales order line this invoice line covers (nullable for ad-hoc lines)
    partida_id          BIGINT REFERENCES doc.partida(id),
    descripcion         TEXT   NOT NULL,
    cantidad            NUMERIC(12,4) NOT NULL CHECK (cantidad > 0),
    unidad_id           INT    NOT NULL REFERENCES unidad(id),
    precio_unitario     NUMERIC(12,4) NOT NULL CHECK (precio_unitario >= 0),
    igv_porcentaje      NUMERIC(5,2)  NOT NULL DEFAULT 18
                            CHECK (igv_porcentaje IN (0, 18)),
    -- Stored computed columns avoid rounding drift across lines
    subtotal_linea      NUMERIC(12,2) GENERATED ALWAYS AS
                            (ROUND(cantidad * precio_unitario, 2)) STORED,
    igv_linea           NUMERIC(12,2) GENERATED ALWAYS AS
                            (ROUND(cantidad * precio_unitario * igv_porcentaje / 100, 2)) STORED,
    total_linea         NUMERIC(12,2) GENERATED ALWAYS AS
                            (ROUND(cantidad * precio_unitario * (1 + igv_porcentaje / 100), 2)) STORED,
    usr_cre INT, fyh_cre TIMESTAMPTZ DEFAULT NOW()
);

GRANT SELECT ON doc.factura         TO authenticated;
GRANT SELECT ON doc.factura_detalle TO authenticated;

-- ── mes.tiempos_estandar_tenido ───────────────────────────────
-- Planning reference: expected duration for a dyeing step given
-- the color depth (valor), dyeing chemistry (tenido), and whether
-- antipilling treatment is included. Computed live at projection
-- time — NOT stored on orden_produccion_paso (which keeps
-- tiempo_estandar only for non-recipe steps copied from template).
CREATE TABLE mes.tiempos_estandar_tenido (
    id              SMALLINT    GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    valor_id        SMALLINT    NOT NULL REFERENCES valor(id),
    tenido_id       INT         NOT NULL REFERENCES tenido(id),
    flg_antipilling BOOLEAN     NOT NULL DEFAULT false,
    duracion        INTERVAL    NOT NULL,
    flg_activo      BOOLEAN     NOT NULL DEFAULT true,
    usr_cre INT, fyh_cre TIMESTAMPTZ DEFAULT NOW(),
    usr_mod INT, fyh_mod TIMESTAMPTZ
);

-- Only one active duration per (color depth, chemistry, antipilling).
CREATE UNIQUE INDEX uq_tiempos_estandar_tenido_activo
    ON mes.tiempos_estandar_tenido(valor_id, tenido_id, flg_antipilling)
    WHERE flg_activo = true;

-- ── mes.tiempos_estandar_lavado ───────────────────────────────
-- Planning reference: expected duration for a wash cycle given the
-- machine wash type. Looked up via receta.lavado_maquina.tipo_lavado_mq_id.
CREATE TABLE mes.tiempos_estandar_lavado (
    id                  SMALLINT    GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tipo_lavado_mq_id   SMALLINT    NOT NULL REFERENCES tipo_lavado_maquina(id),
    duracion            INTERVAL    NOT NULL,
    flg_activo          BOOLEAN     NOT NULL DEFAULT true,
    usr_cre INT, fyh_cre TIMESTAMPTZ DEFAULT NOW(),
    usr_mod INT, fyh_mod TIMESTAMPTZ
);

-- Only one active duration per wash type.
CREATE UNIQUE INDEX uq_tiempos_estandar_lavado_activo
    ON mes.tiempos_estandar_lavado(tipo_lavado_mq_id)
    WHERE flg_activo = true;

