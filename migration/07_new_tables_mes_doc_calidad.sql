-- ── mes.partida_paso_ejecucion ────────────────────────────────
-- AFRU equivalent: actual execution run of a planned step.
-- One partida_paso can have 1..N partida_paso_ejecucion rows (normal run + lagging continuations).
-- A run is created when it starts — no PENDIENTE state.
-- Yield (production output lotes) is posted by registrar_produccion when finalizing the run
-- that generates output (typically the TENIDO step). No schema flag marks this — the
-- caller submits a produccion payload only for the appropriate step.
-- documento reference: inventario.lote and item_movimientos use
--   documento_tipo = 'partida_paso_ejecucion', documento_id = this row's id.
CREATE TABLE mes.partida_paso_ejecucion (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    partida_paso_id bigint NOT NULL REFERENCES mes.partida_paso(id),
    estado          paso_ejecucion_estado_enum NOT NULL DEFAULT 'EN_PROCESO',
    maquina_id      int REFERENCES mes.maquina(id),
    empleado_id     smallint REFERENCES mes.empleado(id),
    fyh_inicio      timestamptz NOT NULL DEFAULT now(),
    fyh_fin         timestamptz,
    ph_real             numeric(4,2),
    temperatura_real    numeric(5,2),
    relacion_bano_real  numeric(5,2),
    cantidad_rollos     numeric(12,4),  -- roll count confirmed in this run (snapshot; ≈ SAP AFRU yield in pieces)
    peso_kg             numeric(12,4),  -- weight processed (snapshot): output lote sum (final step) or prorated input (non-final). Immune to reproceso splits.
    cantidad_scrap      numeric(12,4),  -- rolls condemned mid-execution (≈ SAP AFRU.AFRUASC)
    notas           text,
    programacion_id BIGINT REFERENCES mes.programacion(id),
    usr_cre int,
    fyh_cre TIMESTAMPTZ DEFAULT NOW(),
    usr_mod int,
    fyh_mod TIMESTAMPTZ
);

-- ── mes.partida_componente ────────────────────────────────────
-- Unified reservation table (≈ SAP RESB) covering all components of a partida:
--   Roll rows:     lote_id IS NOT NULL, item_id IS NULL,  partida_paso_id IS NULL
--                  Assigned at order level via actualizar_componentes_partida.
--   Chemical rows: item_id IS NOT NULL, lote_id IS NULL,  partida_paso_id IS NOT NULL
--                  Populated by generar_receta when a recipe step is applied.
--                  cantidad_reservada = recipe qty scaled to actual batch weight.
--                  Serves as the expected consumption baseline for variance alerts.
CREATE TABLE mes.partida_componente (
    id                  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    partida_id          bigint NOT NULL REFERENCES mes.partida(id),
    lote_id             int             REFERENCES inventario.lote(id),
    item_id             int             REFERENCES item(id),
    partida_paso_id     bigint          REFERENCES mes.partida_paso(id) ON DELETE CASCADE,
    cantidad_reservada  numeric(15,7),  -- 7 dp: kg = grams÷1000, preserves 4 gram-decimals (see generar_receta)
    usr_cre int,
    fyh_cre timestamptz DEFAULT now(),
    usr_mod int,
    fyh_mod timestamptz,
    CONSTRAINT chk_resb_tipo CHECK (
        (lote_id IS NOT NULL AND item_id IS NULL  AND partida_paso_id IS NULL)
        OR
        (item_id IS NOT NULL AND lote_id IS NULL  AND partida_paso_id IS NOT NULL)
    )
);
-- One roll per order
CREATE UNIQUE INDEX uq_resb_roll    ON mes.partida_componente(partida_id, lote_id)       WHERE lote_id IS NOT NULL;
-- One chemical reservation per step per item
CREATE UNIQUE INDEX uq_resb_insumo  ON mes.partida_componente(partida_paso_id, item_id)  WHERE item_id IS NOT NULL;

-- ── inventario.pesaje ─────────────────────────────────────────
-- One row per lote. tipo discriminates when/why the weight was recorded:
--   'INGRESO'    — roll weighed at receival (primary flow, registrar_pesaje_produccion)
--   'CORRECCION' — post-assignment weight fix (rare, corregir_pesaje_produccion / actualizar_pesos_individuales_partida)
--   'SALIDA'     — output roll weighed at production time (registrar_produccion)
-- Context is derivable via item_movimientos but tipo avoids the join for simple checks.
CREATE TABLE inventario.pesaje (
    id          INT  GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    lote_id     INT  NOT NULL REFERENCES inventario.lote(id),
    tipo        TEXT NOT NULL CHECK (tipo IN ('INGRESO', 'SALIDA', 'CORRECCION')),
    peso_real   NUMERIC(12,4),
    observacion TEXT,
    usr_cre     INT,
    fyh_cre     TIMESTAMPTZ DEFAULT NOW()
);

-- ── inventario.lote_rollo_detalle ────────────────────────────
-- SAP Batch Classification equivalent for roll lotes.
-- 1:1 extension of inventario.lote for ROLLO lotes.
-- Every ROLLO lote must have exactly one row here (enforced at all creation points).
--
--   item             → stable catalog (what material it is)
--   lote             → physical instance (this specific roll)
--   lote_rollo_detalle → processing state (what has been done to it)
--
-- Attributes set at ingress: guia_remision_id (billing anchor)
-- Physical attributes (ancho, malla, rendimiento): set from partida at production time
