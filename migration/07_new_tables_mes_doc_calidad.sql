-- ── mes.partida ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS mes.partida (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    numero int GENERATED BY DEFAULT AS IDENTITY,
    partida_origen_id bigint REFERENCES mes.partida(id),  -- for reprocessing/rework: link to original order
    prioridad_id int REFERENCES prioridad(id),
    tercero_id INT NOT NULL REFERENCES tercero(id),
    tenido_id int NOT NULL REFERENCES tenido(id),
    color_x_cliente_id int NOT NULL REFERENCES color_x_cliente(id),
    articulo_tipo_id SMALLINT NOT NULL REFERENCES articulo_tipo(id),  -- fabric type for this batch (billing key); restricts assignable rolls
    fibra            SMALLINT NOT NULL,                                -- fiber count; with articulo_tipo_id forms the recipe lookup key
    malla text,
    rendimiento text,
    ancho text,
    flg_antipilling boolean NOT NULL DEFAULT false,
    flg_doble_bolsa boolean NOT NULL DEFAULT false,
    fecha_acordada date,                           -- agreed delivery date with client (SAP: EDATU)
    observacion text,
    estado_produccion partida_estado_produccion_enum NOT NULL DEFAULT 'CREADA',
    -- Billing axis — orthogonal to production state.
    -- Updated when doc.factura lines are issued against this order.
    estado_comercial partida_estado_comercial_enum NOT NULL DEFAULT 'PENDIENTE',
    estado_facturacion partida_facturacion_enum NOT NULL DEFAULT 'pendiente',
    -- Price snapshot — "the price given" for this partida (per-kg rate only; no amounts/IGV/totals).
    -- NULL = derive from doc.catalogo_precios at dispatch date (default, the catalog is the source).
    -- non-NULL = override: a negotiated price, OR a frozen value immutable to later catalog edits.
    -- See migration/patches/26_partida_precio_kg.sql. Added 2026-06-17.
    precio_kg           NUMERIC(10,4) CHECK (precio_kg IS NULL OR precio_kg >= 0),
    CONSTRAINT chk_rework_comercial_locked
        CHECK (partida_origen_id IS NULL OR estado_comercial = 'PENDIENTE'),
    fyh_programacion timestamptz,
    fyh_inicio timestamptz,
    fyh_fin timestamptz,
    usr_cre int,
    fyh_cre TIMESTAMPTZ DEFAULT NOW(),
    usr_mod int,
    fyh_mod TIMESTAMPTZ,
    usr_elm INT,
    fyh_elm TIMESTAMPTZ
);

-- SAP AFPO equivalent: planned output item per production order.
-- cantidad          = planned roll count (AFPO.GAMNG)
-- cantidad_producida = confirmed yield, incremented by registrar_produccion (AFPO.WEMNG)
-- kg breakdown is NOT stored here — derived from item_movimientos PROD_ING rows.
CREATE TABLE IF NOT EXISTS mes.partida_detalle (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    partida_id bigint NOT NULL REFERENCES mes.partida(id),
    item_id int NOT NULL REFERENCES item(id),
    cantidad           numeric(12,2) NOT NULL CHECK (cantidad > 0),
    cantidad_producida numeric(12,2) NOT NULL DEFAULT 0,
    unidad_id int NOT NULL REFERENCES unidad(id),
    usr_cre int,
    fyh_cre TIMESTAMPTZ DEFAULT NOW(),
    usr_mod int,
    fyh_mod TIMESTAMPTZ,
    UNIQUE (partida_id, item_id)
);

